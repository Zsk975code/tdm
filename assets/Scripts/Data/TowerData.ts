export interface TowerConfig {
    type: TowerType;
    name: string;
    cost: number;
    upgradeCost: number;
    damage: number;
    range: number;
    fireRate: number;
    bulletSpeed: number;
    bulletCount: number;
    slowFactor: number;
    slowDuration: number;
    /** 定身时长（秒）：>0 时该塔对范围内敌人施加“完全停止移动”而非减速。雪花塔专用。 */
    freezeDuration: number;
    aoeRadius: number;
    aoeFalloffMin: number;
    maxLevel: number;
    auraRadius: number;
    auraDamageBonus: number;
    periodicAoeInterval: number;
    periodicAoeCount: number;
    hitsAllInRange: boolean;
    maxTargets: number;
    critChance: number;
    critMultiplier: number;
    /** 持续伤害每秒伤害（暮色长弓）：>0 时子弹命中施加持续伤害 DoT；其余塔留空 */
    dotDps?: number;
    /** 持续伤害持续时长（秒）：暮色长弓专用 */
    dotDuration?: number;
    /** 穿云箭触发概率：仅三级>0，触发后该发为穿透主箭（2×伤害·2×素材·命中物品挂毒） */
    penetrateChance?: number;
}

